const messages: Record<AppLocale, Record<TranslationKey, string>> = {
  en: englishMessages,
  ko: koreanMessages
};

type TranslationValues = Record<string, string | number>;

export type LocaleStorage = Pick<Storage, "getItem" | "setItem">;

export function normalizeAppLocale(value: unknown): AppLocale {
  return value === "ko" || value === "en" ? value : defaultAppLocale;
}

export function readStoredAppLocale(storage?: LocaleStorage | null): AppLocale {
  if (!storage) {
    return defaultAppLocale;
  }
  try {
    return normalizeAppLocale(storage.getItem(appLocaleStorageKey));
  } catch {
    return defaultAppLocale;
  }
}

export function writeStoredAppLocale(storage: LocaleStorage | null | undefined, locale: AppLocale): boolean {
  if (!storage) {
    return false;
  }
  try {
    storage.setItem(appLocaleStorageKey, locale);
    return true;
  } catch {
    return false;
  }
}

export function translate(locale: AppLocale, key: TranslationKey, values: TranslationValues = {}): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, () => String(value)),
    messages[locale][key]
  );
}

export type LocalizableWorkflowZoneId = "compose" | "arrange" | "mix" | "deliver";

type LocalizableWorkflowItem = {
  id: LocalizableWorkflowZoneId;
  label: string;
  value: string;
  detail: string;
  tone: "good" | "warn" | "danger";
};

const workflowZoneLabelKeys: Record<LocalizableWorkflowZoneId, TranslationKey> = {
  compose: "nav.compose",
  arrange: "nav.arrange",
  mix: "nav.mix",
  deliver: "nav.deliver"
};

const workflowZoneDetailKeys: Record<LocalizableWorkflowZoneId, TranslationKey> = {
  compose: "nav.composeTabDetail",
  arrange: "nav.arrangeTabDetail",
  mix: "nav.mixTabDetail",
  deliver: "nav.deliverTabDetail"
};

export function localizeWorkflowNavigatorItem(
  locale: AppLocale,
  item: LocalizableWorkflowItem
): Pick<LocalizableWorkflowItem, "label" | "value" | "detail"> {
  if (locale === "en") {
    return {
      label: item.label,
      value: item.value,
      detail: item.detail
    };
  }

  const patternMatch = item.id === "compose" ? /^Pattern\s+(.+)$/u.exec(item.value) : null;
  const barMatch = item.id === "arrange" ? /^(\d+)\s+bars?$/u.exec(item.value) : null;
  const fallbackValueKey: TranslationKey =
    item.tone === "good"
      ? "nav.workflowValueReady"
      : item.tone === "warn"
        ? "nav.workflowValueReview"
        : "nav.workflowValueBlocker";

  return {
    label: translate(locale, workflowZoneLabelKeys[item.id]),
    value: patternMatch
      ? translate(locale, "nav.workflowPatternValue", { pattern: patternMatch[1] ?? "" })
      : barMatch
        ? translate(locale, "nav.workflowBarValue", { count: barMatch[1] ?? "" })
        : translate(locale, fallbackValueKey),
    detail: translate(locale, workflowZoneDetailKeys[item.id])
  };
}

type LocalizationContextValue = {
  locale: AppLocale;
  persistence: LocalePersistence;
  setLocale: (locale: AppLocale) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
};

export type LocalePersistence = "device" | "session";

export function persistAppLocale(storage: LocaleStorage | null | undefined, locale: AppLocale): LocalePersistence {
  return writeStoredAppLocale(storage, locale) ? "device" : "session";
}

export function localePersistenceMessageKeys(persistence: LocalePersistence): {
  detail: TranslationKey;
  title: TranslationKey;
} {
  return persistence === "device"
    ? { detail: "settings.localOnlyDetail", title: "settings.localOnly" }
    : { detail: "settings.sessionOnlyDetail", title: "settings.sessionOnly" };
}

const fallbackLocalization: LocalizationContextValue = {
  locale: defaultAppLocale,
  persistence: "session",
  setLocale: () => undefined,
  t: (key, values) => translate(defaultAppLocale, key, values)
};

const LocalizationContext = createContext<LocalizationContextValue>(fallbackLocalization);

function browserLocaleStorage(): LocaleStorage | null {
  if (typeof window === "undefined") {
    return null;
  }
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

export function LocalizationProvider({
  children,
  initialLocale
}: {
  children: ReactNode;
  initialLocale?: AppLocale;
}): ReactElement {
  const [locale, setLocaleState] = useState<AppLocale>(() =>
    initialLocale ? normalizeAppLocale(initialLocale) : readStoredAppLocale(browserLocaleStorage())
  );
  const [persistence, setPersistence] = useState<LocalePersistence>(() =>
    browserLocaleStorage() ? "device" : "session"
  );

  useEffect(() => {
    document.documentElement.lang = locale;
    window.grooveforge?.setLocale?.(locale);
    setPersistence(persistAppLocale(browserLocaleStorage(), locale));
  }, [locale]);

  const setLocale = useCallback((nextLocale: AppLocale) => {
    const normalized = normalizeAppLocale(nextLocale);
    setLocaleState(normalized);
  }, []);

  const value = useMemo<LocalizationContextValue>(
    () => ({
      locale,
      persistence,
      setLocale,
      t: (key, values) => translate(locale, key, values)
    }),
    [locale, persistence, setLocale]
  );

  return <LocalizationContext.Provider value={value}>{children}</LocalizationContext.Provider>;
}

export function useLocalization(): LocalizationContextValue {
  return useContext(LocalizationContext);
}
